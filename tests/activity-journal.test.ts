import { describe, expect, it } from "vitest";
import { readFileSync } from "node:fs";
import { createActivityJournal } from "../lib/automation-policy";

const metadata={full_name:"owner/repo",default_branch:"main",pushed_at:"2026-09-15T00:00:00Z",open_issues_count:0,visibility:"private"};

describe("transparent activity journal",()=>{
  it("appends one truthful, attributable occurrence and is idempotent",()=>{
    const first=createActivityJournal("",metadata,"2026-09-15","09:00","occurrence-1");
    expect(createActivityJournal(first,metadata,"2026-09-15","09:00","occurrence-1")).toBe(first);
    expect(first).toContain("does not represent source-code work");
    expect(first).toContain("Generated by Commit-Keep");
  });
  it("uses a bounded path and enforces repository restrictions",()=>{
    const execution=readFileSync(new URL("../lib/scheduled-execution.ts",import.meta.url),"utf8");
    expect(execution).toContain(".commitkeep/log/");
    expect(execution).toContain("metadata.archived||metadata.fork");
    expect(execution).toContain("ORGANIZATION_JOURNAL_NOT_ENABLED");
  });
  it("uses an additive migration",()=>{
    const sql=readFileSync(new URL("../drizzle/0010_activity_journal.sql",import.meta.url),"utf8");
    expect(sql).not.toMatch(/DROP TABLE|DELETE FROM/);
  });
});
