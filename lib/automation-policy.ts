export type ScheduleTiming = { timezone: string; localTime: string };
export type ActivityMetadata = { full_name: string; default_branch: string; pushed_at: string; open_issues_count: number; visibility: string };

export function localDayAndTime(date: Date, timezone: string) {
  const parts = new Intl.DateTimeFormat("en-CA", { timeZone: timezone, year: "numeric", month: "2-digit", day: "2-digit", hour: "2-digit", minute: "2-digit", hourCycle: "h23" }).formatToParts(date);
  const value = (type: Intl.DateTimeFormatPartTypes) => parts.find((part) => part.type === type)?.value ?? "";
  return { day: `${value("year")}-${value("month")}-${value("day")}`, time: `${value("hour")}:${value("minute")}` };
}

export function scheduleIsDue(schedule: ScheduleTiming, now: Date) {
  return localDayAndTime(now, schedule.timezone).time >= schedule.localTime;
}

export function createActivityReport(metadata: ActivityMetadata, reportDay: string) {
  return `# Daily repository activity\n\n- Repository: ${metadata.full_name}\n- Report date: ${reportDay}\n- Default branch: ${metadata.default_branch}\n- Visibility: ${metadata.visibility}\n- Last repository push: ${metadata.pushed_at}\n- Open issues and pull requests: ${metadata.open_issues_count}\n\nGenerated by Commit-Keep from GitHub repository metadata.\n`;
}

export function createActivityJournal(existing:string, metadata:ActivityMetadata, localDate:string, localTime:string, occurrenceId:string){
  const marker=`<!-- commitkeep-occurrence:${occurrenceId} -->`;
  if(existing.includes(marker))return existing;
  const heading=existing.trim()?existing.trimEnd():"# Commit-Keep activity journal\n\nGenerated by Commit-Keep. This file records scheduled checks. Entries do not claim source-code, test, or product work.";
  return `${heading}\n\n- ${localDate} ${localTime} — Commit-Keep ran its disclosed activity-journal action for \`${metadata.full_name}\`. This entry was generated by Commit-Keep and does not represent source-code work. ${marker}\n`;
}
